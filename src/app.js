import express from 'express';
import path from 'path';
import cookieParser from 'cookie-parser';
import logger from 'morgan';
import session from 'express-session';
import flash from 'connect-flash';
import expressLayouts from 'express-ejs-layouts';
import healthRoutes from './routes/health.routes.js';
import authRoutes from './routes/auth.routes.js';
import userRoutes from './routes/user.routes.js';
import trackRoutes from './routes/track.routes.js';
import artistRoutes from './routes/artist.routes.js';
import albumRoutes from './routes/album.routes.js';
import genreRoutes from './routes/genre.routes.js';
import playlistRoutes from './routes/playlist.routes.js';
import favoriteRoutes from './routes/favorite.routes.js';
import reviewRoutes from './routes/review.routes.js';
import playbackRoutes from './routes/playback.routes.js';
import dashboardRoutes from './routes/dashboard.routes.js';
import permissionRoutes from './routes/permission.routes.js';
const app = express();
app.set('views', path.join(process.cwd(), 'src/views/pages'));
app.set('layout', path.join(process.cwd(), 'src/views/layouts/main'));
app.use(expressLayouts);
app.set('view engine', 'ejs');
app.use(logger('dev'));
app.use(express.json());
app.use(express.urlencoded({ extended: false }));
app.use(cookieParser());
app.use(express.static(path.join(process.cwd(), 'src/public')));
app.use(session({ secret: process.env.SESSION_SECRET || 'musicvibe-secret-2026', resave: false, saveUninitialized: false, cookie: { maxAge: 1000 * 60 * 60 * 24 } }));
app.use(flash());
app.use((req, res, next) => { res.locals.messages = req.flash(); res.locals.user = req.session.user || null; res.locals.title = 'MusicVibe'; next(); });
app.get('/', (req, res) => res.render('index', { title: 'MusicVibe' }));
app.get('/login', (req, res) => res.render('login', { title: 'Login - MusicVibe' }));
app.get('/register', (req, res) => res.render('register', { title: 'Cadastro - MusicVibe' }));
app.use('/health', healthRoutes);
app.use('/auth', authRoutes);
app.use('/user', userRoutes);
app.use('/track', trackRoutes);
app.use('/artist', artistRoutes);
app.use('/album', albumRoutes);
app.use('/genre', genreRoutes);
app.use('/playlist', playlistRoutes);
app.use('/favorite', favoriteRoutes);
app.use('/review', reviewRoutes);
app.use('/playback', playbackRoutes);
app.use('/dashboard', dashboardRoutes);
app.use('/permission', permissionRoutes);
app.use((req, res) => res.status(404).render('error', { title: 'Página não encontrada' }));
export default app;
