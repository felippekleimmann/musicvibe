import { User } from './User.js';
import { Genre } from './Genre.js';
import { Artist } from './Artist.js';
import { Album } from './Album.js';
import { Track } from './Track.js';
import { Playlist } from './Playlist.js';
import { PlaylistTrack } from './PlaylistTrack.js';
import { Favorite } from './Favorite.js';
import { Review } from './Review.js';
import { PlaybackHistory } from './PlaybackHistory.js';
Artist.hasMany(Album); Album.belongsTo(Artist);
Genre.hasMany(Track); Track.belongsTo(Genre);
Artist.hasMany(Track); Track.belongsTo(Artist);
Album.hasMany(Track); Track.belongsTo(Album);
User.hasMany(Playlist); Playlist.belongsTo(User);
Playlist.belongsToMany(Track, { through: PlaylistTrack }); Track.belongsToMany(Playlist, { through: PlaylistTrack });
User.hasMany(Favorite); Favorite.belongsTo(User); Track.hasMany(Favorite); Favorite.belongsTo(Track); Artist.hasMany(Favorite); Favorite.belongsTo(Artist);
User.hasMany(Review); Review.belongsTo(User); Track.hasMany(Review); Review.belongsTo(Track);
User.hasMany(PlaybackHistory); PlaybackHistory.belongsTo(User); Track.hasMany(PlaybackHistory); PlaybackHistory.belongsTo(Track);
export { User, Genre, Artist, Album, Track, Playlist, PlaylistTrack, Favorite, Review, PlaybackHistory };
